export type IconName = keyof typeof ICONS;

const isIconName = (name: string): name is IconName => name in ICONS;

export function icon(name: IconName | (string & {}), className = ""): SafeHtml {
  const path = isIconName(name) ? ICONS[name] : ICONS.info;
  return raw(
    `<svg class="icon${className ? " " + className : ""}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${path}</svg>`
  );
}

/** Thay các thẻ <i data-icon="name"> viết sẵn trong HTML bằng SVG tương ứng. */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("i[data-icon]").forEach((el) => {
    el.outerHTML = icon(el.dataset.icon ?? "info", el.className).value;
  });
}
